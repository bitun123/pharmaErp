/** Converts a shop name into a clean, URL-safe slug. */
export const slugify = (text: string): string => {
  return text
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
};

const isUniqueViolation = (error: unknown, field?: string): boolean => {
  const e = error as { code?: string; meta?: { target?: unknown } } | null;
  if (e?.code !== "P2002") return false;
  if (!field) return true;
  const target = e.meta?.target;
  return Array.isArray(target) ? target.includes(field) : String(target ?? "").includes(field);
};

const SORTABLE_FIELDS = new Set(["createdAt", "updatedAt", "name", "slug", "shopCode", "isActive"]);

const adminSelect = {
  id: true,
  name: true,
  email: true,
  role: true,
  phoneNumber: true,
  image: true,
} as const;

/**
 * Validates an uploaded logo and returns what must be stored for it.
 * The URL always comes from ImageKit (never from the client), the file must sit in
 * the shops/logos folder, and one file can only be the logo of one shop.
 */
const resolveLogo = async (fileId: string, excludeShopId?: string) => {
  const used = await prisma.shop.findFirst({
    where: { logoFileId: fileId, ...(excludeShopId ? { id: { not: excludeShopId } } : {}) },
    select: { id: true },
  });
  if (used) {
    throw new AppError("LOGO_ALREADY_IN_USE", "This image is already the logo of another shop.", 409);
  }

  const details = await getManagedFileDetails(fileId);
  if (!details.filePath.startsWith("/shops/logos/")) {
    throw new AppError(
      "INVALID_LOGO_FOLDER",
      "The logo must be uploaded to the 'shops/logos' folder.",
      400
    );
  }
  return { logo: details.url, logoFileId: details.fileId, tags: details.tags ?? null };
};

/** Signs out everyone tied to a shop (its admin and members), e.g. when it is blocked or deleted. */
const revokeShopSessions = async (
  tx: Prisma.TransactionClient,
  shopId: string,
  adminId: string | null,
) => {
  const members = await tx.membership.findMany({ where: { shopId }, select: { userId: true } });
  const userIds = [...new Set([...members.map((m) => m.userId), ...(adminId ? [adminId] : [])])];
  if (userIds.length > 0) {
    await tx.session.deleteMany({ where: { userId: { in: userIds } } });
  }
};

/**
 * Finds an available unique slug by appending incremental numeric suffixes if collisions occur.
 * Soft-deleted shops are included because the DB unique index still covers them.
 */
export const getAvailableSlug = async (
  baseSlug: string,
  excludeShopId?: string
): Promise<string> => {
  try {
    const base = baseSlug || "shop";
    let candidate = base;
    let counter = 1;

    while (true) {
      const existing = await prisma.shop.findFirst({
        where: {
          slug: candidate,
          ...(excludeShopId ? { id: { not: excludeShopId } } : {}),
        },
        select: { id: true },
      });

      if (!existing) return candidate;

      candidate = `${base}-${counter}`;
      counter++;
    }
  } catch (error) {
    if (error instanceof AppError) throw error;
    console.error("getAvailableSlug failed:", error);
    throw new AppError("SLUG_GENERATION_FAILED", "Failed to generate a unique slug.", 500);
  }
};

/**
 * Creates a Shop and its Admin user atomically.
 * Nothing is written unless every step succeeds, so a failure can't leave an orphan user,
 * a half-seeded membership or a dangling setup token behind. IDs are generated by the DB.
 */
export const createShopService = async (input: CreateShopInput) => {
  try {
    const normalizedEmail = input.adminEmail.trim().toLowerCase();
    const adminName = input.adminName.trim();
    const shopName = input.name.trim();
    const publicWebUrl = (process.env.PUBLIC_WEB_URL || "http://localhost:3000").replace(/\/+$/, "");
    const rawPassword = input.adminPassword?.trim() || undefined;

    // ---- Pre-checks (read-only, fail fast with friendly messages) ----
    const existingUser = await prisma.user.findUnique({
      where: { email: normalizedEmail },
      select: {
        id: true,
        name: true,
        role: true,
        shop: { select: { name: true } },
        accounts: { where: { providerId: "credential" }, select: { id: true } },
      },
    });

    if (existingUser) {
      if (existingUser.role === "SUPER_ADMIN") {
        throw new AppError(
          "ADMIN_IS_SUPER_ADMIN",
          "This email belongs to a Super Administrator and cannot be assigned as a shop admin.",
          409
        );
      }
      if (existingUser.shop) {
        throw new AppError(
          "ADMIN_ALREADY_ASSIGNED",
          `User '${existingUser.name}' (${normalizedEmail}) is already the administrator of '${existingUser.shop.name}'. Each shop must have a distinct admin.`,
          409
        );
      }
    }

    let finalSlug: string;
    if (input.slug) {
      const slug = slugify(input.slug);
      if (!slug) {
        throw new AppError("INVALID_SLUG", "Slug must contain letters or numbers.", 400);
      }
      const slugConflict = await prisma.shop.findUnique({ where: { slug }, select: { id: true } });
      if (slugConflict) {
        throw new AppError(
          "SLUG_ALREADY_EXISTS",
          `A shop with slug '${slug}' already exists. Please choose a different slug.`,
          409
        );
      }
      finalSlug = slug;
    } else {
      finalSlug = await getAvailableSlug(slugify(shopName));
    }

    // Validate the logo before anything is written. The URL is taken from ImageKit, not the client.
    const logoInfo = input.logoFileId ? await resolveLogo(input.logoFileId) : null;

    // A credential already on file is never overwritten from here.
    const hasCredential = (existingUser?.accounts.length ?? 0) > 0;
    const needsSetupToken = !rawPassword && !hasCredential;
    const hashedPassword = rawPassword && !hasCredential ? await hashPassword(rawPassword) : null;
    const setupToken = needsSetupToken ? crypto.randomBytes(32).toString("hex") : null;
    const setupIdentifier = `set-admin-password:${normalizedEmail}`;

    // ---- Single atomic write ----
    const shop = await prisma.$transaction(async (tx) => {
      const adminUser = existingUser
        ? await tx.user.update({
          where: { id: existingUser.id },
          data: { role: "ADMIN", emailVerified: true },
          select: { id: true },
        })
        : await tx.user.create({
          data: { name: adminName, email: normalizedEmail, role: "ADMIN", emailVerified: true },
          select: { id: true },
        });

      if (hashedPassword) {
        await tx.account.create({
          data: {
            accountId: adminUser.id,
            providerId: "credential",
            userId: adminUser.id,
            password: hashedPassword,
          },
        });
      }

      if (setupToken) {
        await tx.verification.deleteMany({ where: { identifier: setupIdentifier } });
        await tx.verification.create({
          data: {
            identifier: setupIdentifier,
            value: setupToken,
            expiresAt: new Date(Date.now() + 1000 * 60 * 60 * 48),
          },
        });
      }

      const created = await tx.shop.create({
        data: {
          name: shopName,
          slug: finalSlug,
          logo: logoInfo?.logo,
          logoFileId: logoInfo?.logoFileId,
          address: input.address,
          adminId: adminUser.id,
          isActive: input.isActive ?? true,
        },
        include: { admin: { select: adminSelect } },
      });

      await createMembershipForUser(adminUser.id, "ADMIN", created.id, tx);
      return created;
    });

    // The logo is now attached to a shop, so the cleanup script must not touch it.
    if (logoInfo) void markFileAttached(logoInfo.logoFileId, logoInfo.tags);

    const setupUrl = setupToken
      ? `${publicWebUrl}/set-password?token=${setupToken}&email=${encodeURIComponent(normalizedEmail)}`
      : undefined;

    // Email failures must never fail (or crash) a shop that is already created.
    void Promise.resolve(
      sendShopAdminWelcomeEmail({
        email: normalizedEmail,
        name: existingUser?.name ?? adminName,
        shopName: shop.name,
        password: hashedPassword ? rawPassword : undefined,
        setupUrl,
      })
    ).catch((err) => console.error("sendShopAdminWelcomeEmail failed:", err));

    return {
      ...shop,
      adminCredentials: {
        email: normalizedEmail,
        hasDirectLogin: Boolean(hashedPassword) || hasCredential,
        setupUrl: setupUrl || null,
      },
    };
  } catch (error) {
    if (error instanceof AppError) throw error;
    // Lost a race with a concurrent request: the DB unique indexes are the final guard.
    if (isUniqueViolation(error, "slug")) {
      throw new AppError("SLUG_ALREADY_EXISTS", "That slug was just taken. Please try again.", 409);
    }
    if (isUniqueViolation(error, "adminId")) {
      throw new AppError("ADMIN_ALREADY_ASSIGNED", "This user is already a shop administrator.", 409);
    }
    if (isUniqueViolation(error, "logoFileId")) {
      throw new AppError("LOGO_ALREADY_IN_USE", "This image is already the logo of another shop.", 409);
    }
    if (isUniqueViolation(error, "email")) {
      throw new AppError("EMAIL_ALREADY_EXISTS", "A user with this email already exists. Please retry.", 409);
    }
    console.error("createShopService failed:", error);
    throw new AppError("SHOP_CREATE_FAILED", "Failed to create the shop. Please try again.", 500);
  }
};

/**
 * Service to set admin password using the setup token sent via email.
 */
export const setAdminPasswordService = async (input: SetAdminPasswordInput) => {
  try {
    const normalizedEmail = input.email.trim().toLowerCase();
    const token = input.token.trim();
    const password = input.password.trim();

    // 1. Verify token
    const verification = await prisma.verification.findFirst({
      where: {
        identifier: `set-admin-password:${normalizedEmail}`,
        value: token,
        expiresAt: { gt: new Date() },
      },
    });

    if (!verification) {
      throw new AppError(
        "INVALID_OR_EXPIRED_TOKEN",
        "The password setup link is invalid or has expired. Please request a new setup link from your Super Administrator.",
        400
      );
    }

    // 2. Find user
    const user = await prisma.user.findUnique({
      where: { email: normalizedEmail },
      select: { id: true, name: true, email: true },
    });

    if (!user) {
      throw new AppError(
        "USER_NOT_FOUND",
        "Admin user account could not be found.",
        404
      );
    }

    // 3. Hash and store password, and burn the token in the same transaction
    const hashedPassword = await hashPassword(password);

    await prisma.$transaction(async (tx) => {
      const existingAccount = await tx.account.findFirst({
        where: { userId: user.id, providerId: "credential" },
      });

      if (existingAccount) {
        await tx.account.update({
          where: { id: existingAccount.id },
          data: { password: hashedPassword },
        });
      } else {
        await tx.account.create({
          data: {
            accountId: user.id,
            providerId: "credential",
            userId: user.id,
            password: hashedPassword,
          },
        });
      }

      // 4. Invalidate used verification token (all tokens for this email)
      await tx.verification.deleteMany({
        where: { identifier: `set-admin-password:${normalizedEmail}` },
      });
    });

    return {
      success: true,
      message: "Password set successfully. You can now log in to the portal.",
    };
  } catch (error) {
    if (error instanceof AppError) throw error;
    console.error("setAdminPasswordService failed:", error);
    throw new AppError(
      "SET_ADMIN_PASSWORD_FAILED",
      "Failed to set the admin password. Please try again.",
      500
    );
  }
};

/**
 * Service to list shops with pagination, multi-field search, status filtering, and sorting.
 */
export const listShopsService = async (query: ListShopsQuery) => {
  try {
    const page = Math.max(1, Number(query.page) || 1);
    const limit = Math.min(100, Math.max(1, Number(query.limit) || 10));
    const skip = (page - 1) * limit;

    // Build filter criteria
    const where: Prisma.ShopWhereInput = { deletedAt: null };

    // Status filter
    if (query.isActive === "true") {
      where.isActive = true;
    } else if (query.isActive === "false") {
      where.isActive = false;
    }

    // Search filter across name, shopCode, and slug
    if (query.search && query.search.trim()) {
      const searchTerm = query.search.trim();
      where.OR = [
        { name: { contains: searchTerm, mode: "insensitive" } },
        { shopCode: { contains: searchTerm, mode: "insensitive" } },
        { slug: { contains: searchTerm, mode: "insensitive" } },
      ];
    }

    // Sorting
    const sortBy = SORTABLE_FIELDS.has(String(query.sortBy)) ? String(query.sortBy) : "createdAt";
    const sortOrder = query.sortOrder === "asc" ? "asc" : "desc";
    // `id` as a tiebreaker keeps pagination stable when many rows share the sort value.
    const orderBy = [
      { [sortBy]: sortOrder },
      { id: "asc" },
    ] as Prisma.ShopOrderByWithRelationInput[];

    // Fetch count and records in parallel transaction
    const [total, shops] = await prisma.$transaction([
      prisma.shop.count({ where }),
      prisma.shop.findMany({
        where,
        skip,
        take: limit,
        orderBy,
        include: { admin: { select: adminSelect } },
      }),
    ]);

    const totalPages = Math.ceil(total / limit) || 1;

    return {
      data: shops,
      pagination: {
        total,
        page,
        limit,
        totalPages,
        hasNextPage: page < totalPages,
        hasPrevPage: page > 1,
      },
    };
  } catch (error) {
    if (error instanceof AppError) throw error;
    console.error("listShopsService failed:", error);
    throw new AppError(
      "SHOP_LIST_FAILED",
      "Failed to fetch shops. Please try again.",
      500
    );
  }
};

/**
 * Service to fetch a single shop by its unique ID or Slug.
 */
export const getShopByIdService = async (idOrSlug: string) => {
  try {
    if (!idOrSlug || !idOrSlug.trim()) {
      throw new AppError("INVALID_IDENTIFIER", "Shop ID or slug is required.", 400);
    }

    const cleanIdentifier = idOrSlug.trim();

    const shop = await prisma.shop.findFirst({
      where: {
        deletedAt: null,
        OR: [{ id: cleanIdentifier }, { slug: cleanIdentifier }],
      },
      include: { admin: { select: adminSelect } },
    });

    if (!shop) {
      throw new AppError(
        "SHOP_NOT_FOUND",
        `Shop '${cleanIdentifier}' was not found.`,
        404
      );
    }

    return shop;
  } catch (error) {
    if (error instanceof AppError) throw error;
    console.error("getShopByIdService failed:", error);
    throw new AppError(
      "SHOP_FETCH_FAILED",
      "Failed to fetch the shop. Please try again.",
      500
    );
  }
};

/**
 * Service to update an existing shop.
 */
export const updateShopService = async (
  shopId: string,
  input: UpdateShopInput
) => {
  try {
    if (!shopId || !shopId.trim()) {
      throw new AppError("INVALID_SHOP_ID", "Shop ID is required.", 400);
    }

    // 1. Verify shop exists
    const existingShop = await prisma.shop.findFirst({
      where: { id: shopId.trim(), deletedAt: null },
    });

    if (!existingShop) {
      throw new AppError(
        "SHOP_NOT_FOUND",
        `Shop with ID '${shopId}' does not exist.`,
        404
      );
    }

    // 2. Validate slug if being updated
    let finalSlug = existingShop.slug;
    const requestedSlug = input.slug ? slugify(input.slug) : undefined;
    if (input.slug && !requestedSlug) {
      throw new AppError("INVALID_SLUG", "Slug must contain letters or numbers.", 400);
    }
    if (requestedSlug && requestedSlug !== existingShop.slug) {
      const slugConflict = await prisma.shop.findFirst({
        where: {
          slug: requestedSlug,
          id: { not: existingShop.id },
        },
        select: { id: true },
      });

      if (slugConflict) {
        throw new AppError(
          "SLUG_ALREADY_EXISTS",
          `Slug '${requestedSlug}' is already in use.`,
          409
        );
      }
      finalSlug = requestedSlug;
    }

    // 3. Validate adminId if being updated
    const currentAdminId = existingShop.adminId;
    let finalAdminId = currentAdminId;
    if (input.adminId && input.adminId !== currentAdminId) {
      const newAdmin = await prisma.user.findUnique({
        where: { id: input.adminId },
        select: { id: true, name: true, role: true },
      });

      if (!newAdmin) {
        throw new AppError(
          "ADMIN_NOT_FOUND",
          `User with ID '${input.adminId}' does not exist.`,
          404
        );
      }

      if (newAdmin.role === "SUPER_ADMIN") {
        throw new AppError(
          "ADMIN_IS_SUPER_ADMIN",
          "A Super Administrator cannot be assigned as a shop admin.",
          409
        );
      }

      const adminConflict = await prisma.shop.findFirst({
        where: {
          adminId: input.adminId,
          id: { not: existingShop.id },
        },
        select: { id: true },
      });

      if (adminConflict) {
        throw new AppError(
          "ADMIN_ALREADY_ASSIGNED",
          `User '${newAdmin.name}' is already assigned as admin to another shop.`,
          409
        );
      }
      finalAdminId = input.adminId;
    }

    // 3b. Logo: undefined = unchanged, null = remove, string = new ImageKit file id
    let logoData: { logo?: string | null; logoFileId?: string | null } = {};
    let newLogoInfo: Awaited<ReturnType<typeof resolveLogo>> | null = null;
    let logoToDelete: string | null = null;
    if (input.logoFileId === null) {
      if (existingShop.logoFileId) logoToDelete = existingShop.logoFileId;
      logoData = { logo: null, logoFileId: null };
    } else if (input.logoFileId && input.logoFileId !== existingShop.logoFileId) {
      newLogoInfo = await resolveLogo(input.logoFileId, existingShop.id);
      logoData = { logo: newLogoInfo.logo, logoFileId: newLogoInfo.logoFileId };
      logoToDelete = existingShop.logoFileId;
    }

    // 4. Perform update (shop + admin hand-over in one transaction)
    const adminChanged = finalAdminId !== currentAdminId;
    const isBeingBlocked = existingShop.isActive && input.isActive === false;
    const updatedShop = await prisma.$transaction(async (tx) => {
      const updated = await tx.shop.update({
        where: { id: existingShop.id },
        data: {
          name: input.name?.trim() || existingShop.name,
          slug: finalSlug,
          ...logoData,
          // undefined = unchanged, null = cleared
          address: input.address !== undefined ? input.address : existingShop.address,
          adminId: finalAdminId,
          isActive: input.isActive !== undefined ? input.isActive : existingShop.isActive,
        },
        include: { admin: { select: adminSelect } },
      });

      // Move the shop link and ADMIN role from the old admin to the new one
      if (adminChanged && finalAdminId) {
        if (currentAdminId) {
          await tx.membership.updateMany({
            where: { userId: currentAdminId, shopId: updated.id },
            data: { shopId: null },
          });
        }
        await createMembershipForUser(finalAdminId, "ADMIN", updated.id, tx);
        await tx.user.update({ where: { id: finalAdminId }, data: { role: "ADMIN" } });
      }

      // Blocking a shop signs everyone in it out right away.
      if (isBeingBlocked) {
        await revokeShopSessions(tx, updated.id, currentAdminId);
      }
      return updated;
    });

    // ImageKit housekeeping runs after the commit and never fails the request.
    if (newLogoInfo) void markFileAttached(newLogoInfo.logoFileId, newLogoInfo.tags);
    if (logoToDelete) void safeDeleteFile(logoToDelete);

    return updatedShop;
  } catch (error) {
    if (error instanceof AppError) throw error;
    if (isUniqueViolation(error, "slug")) {
      throw new AppError("SLUG_ALREADY_EXISTS", "That slug was just taken.", 409);
    }
    if (isUniqueViolation(error, "adminId")) {
      throw new AppError("ADMIN_ALREADY_ASSIGNED", "That user is already a shop administrator.", 409);
    }
    if (isUniqueViolation(error, "logoFileId")) {
      throw new AppError("LOGO_ALREADY_IN_USE", "This image is already the logo of another shop.", 409);
    }
    console.error("updateShopService failed:", error);
    throw new AppError(
      "SHOP_UPDATE_FAILED",
      "Failed to update the shop. Please try again.",
      500
    );
  }
};

/**
 * Service to delete a shop.
 */
export const deleteShopService = async (shopId: string) => {
  try {
    if (!shopId || !shopId.trim()) {
      throw new AppError("INVALID_SHOP_ID", "Shop ID is required.", 400);
    }

    const existingShop = await prisma.shop.findFirst({
      where: { id: shopId.trim(), deletedAt: null },
      select: { id: true, name: true, slug: true, adminId: true, logoFileId: true },
    });

    if (!existingShop) {
      throw new AppError(
        "SHOP_NOT_FOUND",
        `Shop with ID '${shopId}' was not found.`,
        404
      );
    }

    await prisma.$transaction(async (tx) => {
      // Sign everyone out first (needs the member list while it is still intact).
      await revokeShopSessions(tx, existingShop.id, existingShop.adminId);

      await tx.shop.update({
        where: { id: existingShop.id },
        data: {
          deletedAt: new Date(),
          isActive: false,
          // Free the admin, the slug and the logo so they can be used again.
          // Members keep their shopId on purpose: authenticate() sees the deleted
          // shop and refuses them, so nobody keeps access through it.
          adminId: null,
          slug: `${existingShop.slug}--deleted-${existingShop.id.slice(-8)}`,
          logo: null,
          logoFileId: null,
        },
      });
    });

    // The logo file is no longer referenced anywhere. Best effort, after the commit.
    void safeDeleteFile(existingShop.logoFileId);

    return {
      success: true,
      message: `Shop '${existingShop.name}' has been deleted successfully.`,
      id: existingShop.id,
    };
  } catch (error) {
    if (error instanceof AppError) throw error;
    console.error("deleteShopService failed:", error);
    throw new AppError(
      "SHOP_DELETE_FAILED",
      "Failed to delete the shop. Please try again.",
      500
    );
  }
};
